// Regenerates `probe_columns.js` from the DAX suite in `benchmark/xmla_compare.py`:
//
//     node dashboard/probe_columns.mjs
//
// The report needs to know which column each `probe_<name>` query touches, to put a probe's cold
// cost beside that column's size and encoding. The suite is the only place that says, and
// `data.test.mjs` fails if the committed map drifts from it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { probeMapFrom } from "./data.js";

const HERE = dirname(fileURLToPath(import.meta.url));
export const source = () => readFileSync(join(resolve(HERE, ".."), "benchmark", "xmla_compare.py"), "utf8");
export const moduleText = (map) => "// GENERATED by probe_columns.mjs from benchmark/xmla_compare.py — do not edit by hand.\n" +
  `export const PROBE_COLUMNS = ${JSON.stringify(map, null, 2)};\n`;

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(join(HERE, "probe_columns.js"), moduleText(probeMapFrom(source())));
  process.stderr.write("  wrote dashboard/probe_columns.js\n");
}
