// The data half of the report: run records in, flat rows and statistics out. No DOM, no network
// beyond `loadRemote`, so every number the page prints can be pinned by `node --test`.
//
// Two flat tables carry everything the findings read:
//
//   runs[]     one row per dispatch — who wrote the parquet, its physical shape, and the Direct Lake
//              and DirectQuery cold / warm / hot totals over that dataset's common query set.
//   columns[]  one row per (run, probed column) — the column's compressed size, encoding, dictionary
//              coverage and sort runs beside the cold and warm cost of the probe that touched it.
//
// The rules that keep runs comparable are stated where they are applied: one source generation per
// dataset (`generationOf`), and one query set per dataset (`querySet`).

export const DEFAULTS = { repo: "djouallah/direct-lake-parquet-layout", ref: "main" };

export const DATASETS = {
  aemo: { label: "AEMO", mart: "fct_summary",
    blurb: "electricity dispatch, 5 narrow columns on a regular 5-minute grid" },
  nyc: { label: "NYC taxi", mart: "fct_trips",
    blurb: "yellow taxi trips, 17 columns, several ~99%-one-value categoricals" },
  bts: { label: "BTS flights", mart: "fct_flights",
    blurb: "US on-time flights, 22 columns of independent moderate skew" },
  green: { label: "Green taxi", mart: "fct_green_trips",
    blurb: "green taxi trips, 20 columns, nyc's skew on a smaller table" },
  cms: { label: "CMS payments", mart: "fct_cms_payments",
    blurb: "Open Payments, 91 columns, 54 of them more than half NULL" },
  tpcds: { label: "TPC-DS", mart: "store_sales",
    blurb: "synthetic, generated by dsdgen" },
};

// Below this many runs a range is one lucky dispatch away from saying anything.
export const MIN_RUNS = 3;

// A query enters a dataset's common set when at least this share of its runs carry it with both a
// cold and a warm time. Queries were added and renamed over the project's life; a strict
// intersection would let the oldest record decide the suite for everyone.
export const QUERY_SHARE = 0.6;

// ------------------------------------------------------------------------------------- writers

/** The parquet writer of one record, as a reader would name it, plus the knobs that define it. */
export function writerOf(rec) {
  const e = rec.engine;
  const cfg = ((rec.layout || {}).config || {})[e] || {};
  const ord = ((rec.layout || {}).ordering || {})[e] || {};
  if (e === "duckrun") {
    const sorted = cfg.sorted === true || cfg.sorted === "true";
    return { key: sorted ? "deltars_sorted" : "deltars_unsorted", family: "delta-rs",
      label: sorted ? "delta-rs, sorted" : "delta-rs, unsorted", vorder: false, sorted,
      rgSetting: cfg.row_group_size ? String(cfg.row_group_size) : "16000000" };
  }
  if (e === "iceberg") {
    return { key: "iceberg", family: "duckdb-iceberg", label: "DuckDB → Iceberg", vorder: false,
      sorted: false, rgSetting: cfg.row_group_size ? String(cfg.row_group_size) : null };
  }
  if (e === "spark") {
    const p = cfg.resource_profile || null;
    if (p === "readHeavyForPBI") {
      return { key: "spark_vorder", family: "spark", label: "Spark, V-Order", vorder: true,
        profile: p };
    }
    if (p === "writeHeavy") {
      return { key: "spark_plain", family: "spark", label: "Spark, no V-Order", vorder: false,
        profile: p };
    }
    // A record with no profile recorded predates the input; what it wrote is not knowable from
    // the record, so it is its own writer rather than a guess.
    return { key: p ? `spark_${p}` : "spark_unknown", family: "spark",
      label: p ? `Spark, ${p}` : "Spark, profile not recorded", vorder: p ? false : null,
      profile: p };
  }
  if (e === "dwh") {
    const v = typeof ord.vorder_enabled === "boolean" ? ord.vorder_enabled
      : cfg.vorder === "false" ? false : true;
    return { key: v ? "dwh" : "dwh_novorder", family: "warehouse",
      label: v ? "Warehouse" : "Warehouse, V-Order off", vorder: v };
  }
  return { key: e || "unknown", family: e || "unknown", label: e || "unknown", vorder: null };
}

// Display order and colour slot of every writer the page can meet. Okabe-Ito slots, assigned so the
// writers a reader compares most (the two Spark profiles, delta-rs against Spark) never share a hue.
export const WRITERS = [
  { key: "deltars_sorted", slot: 1 },
  { key: "deltars_unsorted", slot: 6 },
  { key: "spark_vorder", slot: 3 },
  { key: "spark_plain", slot: 2 },
  { key: "dwh", slot: 4 },
  { key: "dwh_novorder", slot: 7 },
  { key: "iceberg", slot: 5 },
];
export const writerSlot = (key) => (WRITERS.find((w) => w.key === key) || { slot: 8 }).slot;

// ------------------------------------------------------------------------------------- flatten

export const datasetOf = (rec) =>
  (rec.inputs || {}).dataset || ((rec.layout || {}).run || {}).dataset || rec.dataset || "aemo";

/** The mart's stats entry for this record's engine, whatever schema prefix the engine used. */
export function martStats(rec) {
  const ds = datasetOf(rec);
  const mart = (DATASETS[ds] || {}).mart;
  const st = (((rec.layout || {}).stats || {})[rec.engine]) || {};
  const k = Object.keys(st).find((n) => n === mart || n.endsWith(`.${mart}`));
  return k ? st[k] : null;
}

/** `{dl: {qid: q}, dq: {qid: q}}` — DirectQuery models carry the `_dq` suffix, nothing else does. */
export function timingsOf(rec) {
  const t = ((rec.benchmark || {}).timings) || {};
  const out = { dl: {}, dq: {} };
  for (const [model, qs] of Object.entries(t)) {
    Object.assign(model.endsWith("_dq") ? out.dq : out.dl, qs || {});
  }
  return out;
}

const tierOf = (q, tier) => {
  if (!q) return null;
  const v = tier === "cold" ? q.cold_ms : tier === "warm" ? q.warm_ms : q.hot_median_ms;
  return typeof v === "number" && v > 0 ? v : null;
};

/** One flat row per record; physical layout only, totals are added by `build`. */
export function flattenRun(rec) {
  const w = writerOf(rec);
  const s = martStats(rec) || {};
  const rows = typeof s.total_rows === "number" ? s.total_rows : null;
  const rgs = typeof s.num_row_groups === "number" ? s.num_row_groups : null;
  return {
    id: String(((rec.run || {}).id) || rec._file || ""),
    file: rec._file || "",
    when: ((rec.run || {}).started || "").slice(0, 10),
    url: (rec.run || {}).url || "",
    ds: datasetOf(rec), engine: rec.engine,
    writer: w.key, writerLabel: w.label, family: w.family, vorder: w.vorder,
    sorted: !!w.sorted, rgSetting: w.rgSetting || null,
    // Whether the writer reorders rows before writing — a global sort or V-Order. The one physical
    // property every chart marks the same way (filled against hollow).
    reorders: !!(w.vorder || w.sorted),
    sortAuto: ((((rec.dbt || {})[rec.engine]) || {}).sort_by_auto) || null,
    rows, files: s.num_files ?? null, rgs,
    rowsPerRg: rows && rgs ? rows / rgs : null,
    mb: typeof s.size_mb === "number" ? s.size_mb : null,
    compression: s.compression || null,
    timings: timingsOf(rec),
    encodings: (((rec.layout || {}).encodings) || {})[rec.engine] || null,
    ordering: ((((rec.layout || {}).ordering) || {})[rec.engine] || {}).columns || null,
    // How many rows the sort-runs count was taken over (at most 4M, from the largest file), so a
    // run count can be read as a rate rather than a number that grows with the sample.
    sampleRows: (((((rec.layout || {}).ordering) || {})[rec.engine] || {}).sample || {}).rows || null,
  };
}

// ------------------------------------------------------------------------------ comparability

/**
 * The mart row count a dataset's runs are compared at: the BIGGEST one recorded. The archive only
 * grows, so the biggest generation has the most data behind it, and a run measured on a smaller
 * slice is a different workload rather than a faster one. A run that recorded no row count is
 * kept: unmeasured is a different claim from different.
 */
export function generationOf(runs) {
  const counts = runs.map((r) => r.rows).filter((n) => typeof n === "number");
  return counts.length ? Math.max(...counts) : null;
}

/** The queries at least `QUERY_SHARE` of the runs carry with both a cold and a warm time. */
export function querySet(runs, phase = "dl") {
  const seen = new Map();
  // Only runs that measured this phase at all vote: the DirectQuery phase is younger than the
  // Direct Lake one, and runs from before it existed would otherwise veto every DQ query.
  const voters = runs.filter((r) => Object.keys(r.timings[phase] || {}).length);
  for (const r of voters) {
    for (const [qid, q] of Object.entries(r.timings[phase] || {})) {
      if (tierOf(q, "cold") && tierOf(q, "warm")) seen.set(qid, (seen.get(qid) || 0) + 1);
    }
  }
  const need = Math.max(1, Math.ceil(voters.length * QUERY_SHARE));
  return [...seen].filter(([, n]) => n >= need).map(([q]) => q).sort();
}

/** The run's sum of one tier over `qids`, or null when it is missing any of them. */
export function totalOf(run, phase, tier, qids) {
  if (!qids.length) return null;
  let sum = 0;
  for (const q of qids) {
    const v = tierOf((run.timings[phase] || {})[q], tier);
    if (v === null) return null;
    sum += v;
  }
  return sum;
}

// ------------------------------------------------------------------------------- probe columns

/** probe name (without `probe_`) -> column, per mart. Generated from benchmark/xmla_compare.py. */
export function probeMapFrom(pythonSource) {
  const out = {};
  const re = /\(\s*"probe"\s*,\s*"probe_(\w+)"\s*,\s*'[^']*?\b(\w+)\[(\w+)\]/g;
  let m;
  while ((m = re.exec(pythonSource))) {
    if (m[1] === "rowcount") continue;
    (out[m[2]] = out[m[2]] || {})[m[1]] = m[3];
  }
  return out;
}

const lowerKeys = (o) => Object.fromEntries(Object.entries(o || {}).map(([k, v]) => [k.toLowerCase(), v]));

/**
 * One row per (run, probed column). A probe's marginal cost is its time minus `probe_rowcount`'s at
 * the same pass, which is what isolates loading THAT column from the fixed cost of any query —
 * the same decomposition the benchmark's own report makes.
 */
export function flattenColumns(run, probeMap) {
  const map = (probeMap || {})[(DATASETS[run.ds] || {}).mart] || {};
  const dl = run.timings.dl || {};
  const base = dl.probe_rowcount;
  if (!base) return [];
  const enc = lowerKeys(run.encodings);
  const ord = lowerKeys(run.ordering);
  const out = [];
  for (const [probe, col] of Object.entries(map)) {
    const q = dl[`probe_${probe}`];
    if (!q) continue;
    const e = enc[col.toLowerCase()];
    const o = ord[col.toLowerCase()];
    const marginal = (tier) => {
      const a = tierOf(q, tier), b = tierOf(base, tier);
      return a !== null && b !== null ? a - b : null;
    };
    out.push({
      runId: run.id, ds: run.ds, writer: run.writer, writerLabel: run.writerLabel,
      family: run.family, reorders: run.reorders,
      column: col, probe,
      mb: e && typeof e.mb === "number" ? e.mb : null,
      type: e ? e.type || null : null,
      encodings: e ? (e.encodings || []).join("+") : null,
      dictFull: e && e.chunks ? e.dict_pages === e.chunks : null,
      dictPages: e ? e.dict_pages ?? null : null, chunks: e ? e.chunks ?? null : null,
      // From the footer's own `encoding_stats` (stats.py, absent on records written before it read
      // them): chunks that declare their page encodings at all, and chunks declared ENTIRELY
      // dictionary-encoded — the ones Direct Lake can remap instead of hashing every value.
      declared: e && typeof e.declared === "number" ? e.declared : null,
      dictDeclared: e && typeof e.dict_declared === "number" ? e.dict_declared : null,
      // Remap-eligible: every chunk of the column declared fully dictionary-encoded.
      remap: e && typeof e.dict_declared === "number" && e.chunks ? e.dict_declared === e.chunks : null,
      runs: o && typeof o.runs === "number" ? o.runs : null,
      runsPer1k: o && typeof o.runs === "number" && run.sampleRows ? (o.runs / run.sampleRows) * 1000 : null,
      cold: marginal("cold"), warm: marginal("warm"),
      coldRaw: tierOf(q, "cold"), warmRaw: tierOf(q, "warm"),
    });
  }
  return out;
}

// ------------------------------------------------------------------------------------- capacity
//
// What READING the table cost, in Fabric capacity units, from `history/cu.json` (written by
// `cu/measure.py`). Each query phase owns its own items, created and deleted inside one run: the
// semantic model, the shortcut lakehouse it reads through (OneLake bills a read against the item
// hosting the shortcut), and that lakehouse's SQL analytics endpoint, which carries the role
// `sql_endpoint` and is matched to its phase by NAME. For DirectQuery that endpoint's
// `SQL Endpoint Query` CU is most of the bill. The figure covers the whole session — the cold pass,
// the warm pass and the hot passes together — so it has no cold/warm split.

export const PHASE_ROLES = { dl: ["semantic_model", "bench_dl"], dq: ["semantic_model_dq", "bench_dq"] };

/** `{dl, dq}` capacity units for one record; null for a phase the ledger has not read. */
export function readCu(rec, ledger) {
  const items = (rec && rec.items) || {};
  const led = ((ledger || {}).items) || {};
  const out = {};
  for (const [phase, roles] of Object.entries(PHASE_ROLES)) {
    const lakehouses = new Set(Object.values(items).filter((it) => it && roles.slice(1).includes(it.role) && it.name)
      .map((it) => it.name));
    const guids = Object.entries(items).filter(([, it]) => it && (roles.includes(it.role)
      || (it.role === "sql_endpoint" && lakehouses.has(it.name)))).map(([g]) => g);
    // A session's bill is only whole when its semantic model was billed: without it, what is left is
    // the shortcut lakehouse's few CU (runs 35184037336, 34563142340 read 15 and 16 CU that way).
    const model = Object.entries(items).find(([, it]) => it && it.role === roles[0]);
    if (!model || led[model[0]] === undefined || led[model[0]] === null) { out[phase] = null; continue; }
    let sum = 0, seen = false;
    for (const g of guids) {
      const v = led[g];
      if (v === undefined || v === null) continue;
      seen = true;
      sum += typeof v === "object" ? Object.values(v).reduce((a, b) => a + Number(b || 0), 0) : Number(v);
    }
    out[phase] = seen && sum > 0 ? sum : null;
  }
  return out;
}

// ---------------------------------------------------------------------------------------- build

/**
 * Everything the report reads: `{runs, columns, perDataset, excluded}`.
 *
 * Per dataset: drop runs from another generation, fix the query set, then give every run its six
 * totals (Direct Lake and DirectQuery × cold / warm / hot). A run missing a query in the set keeps
 * its layout row and gets null totals, so it still feeds the layout-only findings.
 */
export function build(records, probeMap, ledger = null) {
  const all = records.filter((r) => r && r.engine).map((rec) => ({ ...flattenRun(rec), cu: readCu(rec, ledger) }));
  const runs = [], excluded = [], perDataset = {};
  for (const ds of Object.keys(DATASETS)) {
    const mine = all.filter((r) => r.ds === ds);
    if (!mine.length) continue;
    const gen = generationOf(mine);
    const kept = mine.filter((r) => r.rows === null || gen === null || r.rows === gen);
    for (const r of mine) if (!kept.includes(r)) excluded.push({ ...r, reason: `${fmtInt(r.rows)} rows, not ${fmtInt(gen)}` });
    const qDl = querySet(kept, "dl"), qDq = querySet(kept, "dq");
    for (const r of kept) {
      r.dl = { cold: totalOf(r, "dl", "cold", qDl), warm: totalOf(r, "dl", "warm", qDl),
        hot: totalOf(r, "dl", "hot", qDl) };
      r.dq = { cold: totalOf(r, "dq", "cold", qDq), warm: totalOf(r, "dq", "warm", qDq),
        hot: totalOf(r, "dq", "hot", qDq) };
      // A session that did not complete the query suite billed part of one (run 31850696469 died on a
      // year-0002 date mid-suite and read 525 CU against a median of 1,649), so its read CU is not a
      // measurement of reading that layout.
      if (r.dl.cold === null) r.cu = { ...r.cu, dl: null };
      if (r.dq.cold === null) r.cu = { ...r.cu, dq: null };
      runs.push(r);
    }
    perDataset[ds] = { rows: gen, runs: kept.length, queriesDl: qDl, queriesDq: qDq };
  }
  const columns = runs.flatMap((r) => flattenColumns(r, probeMap));
  return { runs, columns, perDataset, excluded };
}

// ----------------------------------------------------------------------------------- statistics

export function median(xs) {
  const v = xs.filter((x) => typeof x === "number" && Number.isFinite(x)).sort((a, b) => a - b);
  if (!v.length) return null;
  const m = v.length >> 1;
  return v.length % 2 ? v[m] : (v[m - 1] + v[m]) / 2;
}

function ranks(v) {
  const order = v.map((x, i) => [x, i]).sort((a, b) => a[0] - b[0]);
  const r = new Array(v.length);
  for (let i = 0; i < order.length;) {
    let j = i;
    while (j + 1 < order.length && order[j + 1][0] === order[i][0]) j++;
    for (let k = i; k <= j; k++) r[order[k][1]] = (i + j) / 2;
    i = j + 1;
  }
  return r;
}

/** Spearman's rank correlation, ties averaged; null below 5 pairs, where it means nothing. */
export function spearman(xs, ys) {
  const pairs = xs.map((x, i) => [x, ys[i]])
    .filter(([x, y]) => Number.isFinite(x) && Number.isFinite(y));
  if (pairs.length < 5) return null;
  const a = ranks(pairs.map((p) => p[0])), b = ranks(pairs.map((p) => p[1]));
  const ma = a.reduce((s, x) => s + x, 0) / a.length, mb = b.reduce((s, x) => s + x, 0) / b.length;
  let num = 0, da = 0, db = 0;
  for (let i = 0; i < a.length; i++) {
    num += (a[i] - ma) * (b[i] - mb); da += (a[i] - ma) ** 2; db += (b[i] - mb) ** 2;
  }
  return da && db ? num / Math.sqrt(da * db) : null;
}

/** Plain words for a correlation, so a claim sentence never prints a bare ρ. */
export function strength(rho) {
  if (rho === null) return "too few points";
  const a = Math.abs(rho);
  return a >= 0.7 ? "strong" : a >= 0.4 ? "moderate" : a >= 0.2 ? "weak" : "none";
}

/**
 * Compare groups of per-run values (lower is better). `clear` only when every run of the best group
 * beat every run of every other group, with at least `MIN_RUNS` each; `few` when some group is
 * thinner than that; `noise` otherwise. Strict on purpose: the audience reads a label, not a spread.
 */
export function verdict(groups) {
  const present = Object.entries(groups).map(([k, v]) => [k, v.filter((x) => x > 0)])
    .filter(([, v]) => v.length);
  if (present.length < 2) return { status: "few", best: null };
  if (present.some(([, v]) => v.length < MIN_RUNS)) {
    return { status: "few", best: present.reduce((a, b) => (median(b[1]) < median(a[1]) ? b : a))[0] };
  }
  const [best, bv] = present.reduce((a, b) => (median(b[1]) < median(a[1]) ? b : a));
  const worstOfBest = Math.max(...bv);
  const clear = present.every(([k, v]) => k === best || worstOfBest < Math.min(...v));
  return { status: clear ? "clear" : "noise", best };
}

// ---------------------------------------------------------------------------------------- format

export function fmtCu(cu) {
  if (typeof cu !== "number") return "—";
  return `${cu >= 10000 ? (cu / 1000).toFixed(0) + "k" : cu >= 1000 ? (cu / 1000).toFixed(1) + "k" : Math.round(cu)} CU`;
}
export const fmtInt = (n) => (typeof n === "number" ? Math.round(n).toLocaleString("en-US") : "—");
export function fmtMs(ms) {
  if (typeof ms !== "number") return "—";
  if (Math.abs(ms) >= 10000) return `${(ms / 1000).toFixed(0)} s`;
  if (Math.abs(ms) >= 1000) return `${(ms / 1000).toFixed(1)} s`;
  return `${Math.round(ms)} ms`;
}
export function fmtMb(mb) {
  if (typeof mb !== "number") return "—";
  if (mb >= 1024) return `${(mb / 1024).toFixed(1)} GB`;
  if (mb >= 10) return `${Math.round(mb)} MB`;
  if (mb >= 0.1) return `${mb.toFixed(1)} MB`;
  return `${Math.max(1, Math.round(mb * 1024))} KB`;
}
export const fmtX = (x) => (typeof x === "number" ? `${x >= 10 ? x.toFixed(0) : x.toFixed(1)}×` : "—");
export function fmtRows(n) {
  if (typeof n !== "number") return "—";
  if (n >= 9.95e8) return `${(n / 1e9).toFixed(1)}B`;
  if (n >= 9.95e5) return `${(n / 1e6).toFixed(n >= 9.95e6 ? 0 : 1)}M`;
  if (n >= 1e3) return `${(n / 1e3).toFixed(0)}K`;
  return String(n);
}

// ----------------------------------------------------------------------------------------- load

async function jsonOf(url, fetchImpl) {
  const r = await fetchImpl(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.json();
}

/** Every committed run record and the CU ledger, read at view time from raw.githubusercontent.com. */
export async function loadRemote(opts = {}) {
  const repo = opts.repo || DEFAULTS.repo, ref = opts.ref || DEFAULTS.ref;
  const fetchImpl = opts.fetch || fetch;
  const raw = `https://raw.githubusercontent.com/${repo}/${ref}/`;
  const keep = (n) => typeof n === "string" && n.endsWith(".json") && n !== "index.json" && !n.includes("/");
  let names = await jsonOf(raw + "history/runs/index.json", fetchImpl).catch(() => null);
  names = Array.isArray(names) ? names.filter(keep).sort() : [];
  if (!names.length) {
    const api = `https://api.github.com/repos/${repo}/contents/history/runs?ref=${encodeURIComponent(ref)}`;
    const listing = await jsonOf(api, fetchImpl);
    names = (Array.isArray(listing) ? listing : []).filter((e) => e.type === "file" && keep(e.name))
      .map((e) => e.name).sort();
  }
  const [ledger, ...records] = await Promise.all([
    jsonOf(raw + "history/cu.json", fetchImpl).catch(() => null),
    ...names.map((n) => jsonOf(raw + "history/runs/" + n, fetchImpl)
      .then((r) => Object.assign(r, { _file: n })).catch(() => null))]);
  return { records: records.filter(Boolean), ledger };
}
